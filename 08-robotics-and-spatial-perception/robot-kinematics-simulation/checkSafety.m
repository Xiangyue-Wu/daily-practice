function is_safe = checkSafety(robot_position, safe_region)
    % 检查位置是否在安全区域内
    % 输入：
    %   robot_position: [x, y, z] 机器人当前位置
    %   safe_region: [xmin, xmax, ymin, ymax, zmin, zmax] 安全区域边界
    % 输出：
    %   is_safe: 布尔值，true表示安全，false表示危险
    
    is_safe = (robot_position(1) >= safe_region(1)) && ...
              (robot_position(1) <= safe_region(2)) && ...
              (robot_position(2) >= safe_region(3)) && ...
              (robot_position(2) <= safe_region(4)) && ...
              (robot_position(3) >= safe_region(5)) && ...
              (robot_position(3) <= safe_region(6));
end